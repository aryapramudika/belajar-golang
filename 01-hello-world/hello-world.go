package main

//import package lain, bernama fmt, dimana fmt ini package yang digunakan untuk handle I/O teks
import "fmt"

// buat function main (utama), function ini akan dijalankan secara default ketika program dijalankan.
func main() {
	//fmt untuk manipulasi teks, lalu panggil Println dimana untuk mencetak teks
	fmt.Println("Hello", "Arya", "Pramudika!!")
	/*
		Komentar multiline
		jadi gw bisa comment disini dengan banyak
		contoh gw mau cetak teks lagi
	*/
	fmt.Println("Halo", "Juga")
}
